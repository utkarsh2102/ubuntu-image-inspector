/**
 * The LLM panel.
 *
 * Generated text is kept visually and structurally separate from the measured
 * figures: its own container, its own header naming the model, evidence chips
 * that jump to the deterministic row a claim came from, and a wavy underline on
 * any number that is not in the evidence pack.
 */
import { el, clear } from '../util/dom.js';
import { complete, PROVIDERS } from './provider.js';
import { loadConfig, saveConfig } from './keystore.js';
import { buildEvidencePack, packNumbers } from './evidence.js';
import { SYSTEM_PROMPT, buildUserMessage, parseResponse, verifyNumbers } from './prompt.js';

let lastPack = null;

export function currentPack() {
  return lastPack;
}

export function preparePack(ctx) {
  lastPack = buildEvidencePack(ctx);
  return lastPack;
}

export function renderSettings(root) {
  const cfg = loadConfig();
  clear(root);

  const providerSel = el(
    'select',
    { id: 'llm-provider' },
    Object.values(PROVIDERS).map((p) =>
      el('option', { value: p.id, text: p.label, selected: p.id === cfg.provider })
    )
  );
  const modelInput = el('input', {
    type: 'text',
    id: 'llm-model',
    value: cfg.model || PROVIDERS[cfg.provider]?.defaultModel || '',
    placeholder: 'model id',
  });
  const baseInput = el('input', {
    type: 'text',
    id: 'llm-base',
    value: cfg.baseUrl || '',
    placeholder: PROVIDERS[cfg.provider]?.defaultBaseUrl || 'https://…',
  });
  const keyInput = el('input', {
    type: 'password',
    id: 'llm-key',
    value: cfg.apiKey || '',
    placeholder: PROVIDERS[cfg.provider]?.keyHint || 'API key',
    autocomplete: 'off',
  });
  const remember = el('input', { type: 'checkbox', id: 'llm-remember', checked: cfg.remember });

  providerSel.addEventListener('change', () => {
    const p = PROVIDERS[providerSel.value];
    modelInput.value = p.defaultModel || '';
    baseInput.placeholder = p.defaultBaseUrl || 'https://…';
    keyInput.placeholder = p.keyHint || 'API key';
  });

  root.append(
    el('div', { class: 'controls', style: { marginTop: '10px' } }, [
      el('label', { class: 'field' }, [el('span', { text: 'Provider' }), providerSel]),
      el('label', { class: 'field' }, [el('span', { text: 'Model' }), modelInput]),
      el('label', { class: 'field' }, [el('span', { text: 'Base URL' }), baseInput]),
      el('label', { class: 'field' }, [el('span', { text: 'API key' }), keyInput]),
      el('label', { class: 'field' }, [
        el('span', { text: 'Remember' }),
        el('span', {}, [remember, ' on this device']),
      ]),
      el('button', {
        class: 'btn',
        type: 'button',
        text: 'Save',
        onclick: () => {
          saveConfig({
            provider: providerSel.value,
            model: modelInput.value.trim(),
            baseUrl: baseInput.value.trim(),
            apiKey: keyInput.value,
            remember: remember.checked,
          });
          root.append(el('p', { class: 'note', text: 'Saved.' }));
        },
      }),
    ])
  );

  root.append(
    el('p', {
      class: 'note',
      text:
        'Your key goes directly from this browser to the provider. This site has no backend and ' +
        'never receives it. Stored in sessionStorage unless you tick Remember.',
    })
  );
  const p = PROVIDERS[cfg.provider];
  if (p?.note) root.append(el('p', { class: 'warn', text: p.note }));
}

export async function runAnalysis(root, onRefClick) {
  const cfg = loadConfig();
  if (!lastPack) {
    clear(root);
    root.append(el('p', { class: 'warn', text: 'Select a comparison and image first.' }));
    return;
  }
  if (!cfg.apiKey && cfg.provider !== 'custom') {
    clear(root);
    root.append(
      el('p', {
        class: 'warn',
        text: 'No API key configured. Use “Provider…” to add one, or “Copy evidence pack” to paste the facts into Claude Code or any chat.',
      })
    );
    return;
  }

  clear(root);
  root.append(el('p', { class: 'note', text: 'Analysing…' }));

  try {
    const text = await complete(cfg, {
      system: SYSTEM_PROMPT,
      user: buildUserMessage(lastPack),
    });
    renderResult(root, parseResponse(text), cfg, onRefClick);
  } catch (err) {
    clear(root);
    root.append(el('p', { class: 'warn', text: String(err.message || err) }));
  }
}

export function renderResult(root, result, cfg, onRefClick) {
  clear(root);
  const nums = packNumbers(lastPack);

  const box = el('div', { class: 'llm__out' });
  box.append(
    el('div', {
      class: 'llm__head',
      text: `Interpretation — generated by ${cfg.model || PROVIDERS[cfg.provider]?.defaultModel || cfg.provider}`,
    })
  );

  if (result.summary) box.append(annotate(result.summary, nums, 'p'));

  if (result.findings?.length) {
    const ul = el('ul');
    for (const f of result.findings) {
      const li = el('li', { class: 'finding' });
      li.append(annotate(f.claim, nums, 'span'));
      for (const ref of f.evidenceRefs || []) {
        li.append(
          el('button', {
            class: 'evref',
            type: 'button',
            text: ref,
            title: 'Show the measured row this claim came from',
            onclick: () => onRefClick && onRefClick(ref),
          })
        );
      }
      if (f.confidence) li.append(el('span', { class: 'pill', text: f.confidence }));
      ul.append(li);
    }
    box.append(ul);
  }

  if (result.unknowns?.length) {
    box.append(el('div', { class: 'llm__head', text: 'Stated as not established' }));
    box.append(el('ul', {}, result.unknowns.map((u) => el('li', { text: u }))));
  }
  if (result.suggestedFollowUps?.length) {
    box.append(el('div', { class: 'llm__head', text: 'Suggested follow-ups' }));
    box.append(el('ul', {}, result.suggestedFollowUps.map((u) => el('li', { text: u }))));
  }

  box.append(
    el('div', {
      class: 'llm__foot',
      text:
        'Generated text. Every figure in the sections above this panel is measured from the ' +
        'manifests; this narrative is not. Numbers not found in the evidence pack are underlined.',
    })
  );
  root.append(box);
}

/** Wrap any number not present in the pack so it is visibly unverified. */
function annotate(text, nums, tag) {
  const node = el(tag);
  const bad = new Set(verifyNumbers(text, nums));
  if (!bad.size) {
    node.textContent = text;
    return node;
  }
  const parts = String(text).split(/(\d[\d,.]*)/g);
  for (const part of parts) {
    if (bad.has(part)) node.append(el('span', { class: 'unverified', text: part, title: 'not found in the evidence pack' }));
    else node.append(part);
  }
  return node;
}
